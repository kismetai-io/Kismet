// Recoverable per-run checkpoints.
//
// The diff UI's Reject used to delete the nodes an agent added (by name) and
// put back pin defaults, from a baseline that lived only in memory. It did not
// restore a node the agent deleted, a link it broke or a variable it added,
// it overwrote edits a person made after the run, it never touched the file
// the autosave had already written, and after a restart it had nothing to
// restore from. It always reported "Changes rejected".
//
// ── Scope ────────────────────────────────────────────────────────────────────
// One checkpoint per (session, run, asset), taken immediately before the run's
// first mutating call to that asset (FKismetAIAgent -> BeginMutation). It is
// the whole package as it was in memory at that moment — including edits the
// user had not saved — written with the editor's autosave flags (a copy; the
// live package keeps its file, path and dirty flag). Supported assets are the
// ones KismetAIAssetState describes (Blueprints, materials) in a file-backed
// package that is not a map. Anything else gets a manifest that says why it
// cannot be restored, so a Reject reports "unsupported" instead of guessing.
// Assets the run created are not checkpointed (nothing to restore to) and are
// reported; deleting them is left to the user.
//
// ── On disk ──────────────────────────────────────────────────────────────────
//   <Saved>/KismetAI/checkpoints/<session>/<run>/<asset key>/
//     manifest.json     format kismet_checkpoint/1 (below), written atomically
//     checkpoint.uasset the package before the run
//     result.uasset     the package as the run left it, written by a restore
//                       (what Reapply puts back)
// manifest.json: session_id, run_id, asset, asset_class, created_at,
//   engine_version, package_file_version (UE5), restorable / unrestorable_reason,
//   package_was_dirty (the checkpoint holds edits that were unsaved),
//   checkpoint {file, sha1, size, fingerprint (live state it was saved from),
//   file_fingerprint (the state LOADING the copy produces; checked when the
//   checkpoint is written), load_differences (what loading re-derives
//   differently, e.g. class defaults regenerated by a compile on load)},
//   result {same, for the run's result; written by a restore}, last_agent_fingerprint (state
//   after the run's latest call), foreign_change + foreign_evidence (the asset
//   changed between two of the run's calls, i.e. not by the run), status
//   (pending | accepted | restored | restore_failed | unresolved), history[].
//
// ── Lifecycle ────────────────────────────────────────────────────────────────
//   pending    created; the run's calls update last_agent_fingerprint
//   accepted   Accept: the files are deleted, the manifest stays as a receipt
//   restored   Restore succeeded and was verified
//   restore_failed / unresolved   kept, with the reason, for the user
// Startup prunes run folders whose checkpoints are all accepted or restored,
// and any folder older than the retention period (14 days).
//
// ── Restore preconditions (checked before anything is touched) ───────────────
//   1. the manifest reads, is this format, and its engine/package version is
//      this build's (else checkpoint_corrupt / checkpoint_incompatible);
//   2. the checkpoint file exists and its SHA-1 matches (else
//      checkpoint_unavailable / checkpoint_corrupt);
//   3. the checkpoint is restorable (else unsupported);
//   4. no change outside the run was seen between its calls, and the asset now
//      equals the run's last recorded state (else conflict: restoring would
//      discard someone's work; nothing is changed);
//   5. the checkpoint file, loaded as a separate copy, describes exactly the
//      file_fingerprint recorded when it was written (else checkpoint_unverifiable).
// Then: the package is fully loaded and its loader detached (as source control
// revert does), the live state is saved to result.uasset, the checkpoint bytes
// replace the package file, and the package is RELOADED from that file
// (UPackageTools::ReloadPackages) — memory is made to follow disk, never
// assumed to. Finally the reloaded state is compared with file_fingerprint and
// the file's SHA-1 with the checkpoint's. Only that comparison reports
// `restored`; load_differences are listed in the report's evidence.
// If the asset already equals the target in memory AND its file describes the
// same state (an unsaved run lost in a restart), nothing is written and the
// report says so.
//
// ── Failure ──────────────────────────────────────────────────────────────────
//   writing the file fails   restore_failed; the previous file is put back;
//                            memory was never touched
//   reload fails             the previous file is put back: restore_failed with
//                            memory = run result, disk = run result; if putting
//                            it back fails too: unresolved, memory = run result,
//                            disk = checkpoint (stated, never hidden)
//   verification fails       unresolved: memory and disk agree with each other
//                            (memory was reloaded from disk) but not with the
//                            checkpoint; the differences are listed
// No outcome other than `restored` claims the asset is back.
//
// Game thread only.

#pragma once

#include "CoreMinimal.h"
#include "KismetAIMutationIntent.h"
#include "Dom/JsonObject.h"

enum class EKismetAIRestoreStatus : uint8
{
	Restored,
	Conflict,
	CheckpointUnavailable,
	CheckpointCorrupt,
	CheckpointIncompatible,
	CheckpointUnverifiable,
	Unsupported,
	RestoreFailed,
	Unresolved,
};

struct FKismetAIRestoreReport
{
	FString SessionId;
	FString RunId;
	FString AssetPath;
	EKismetAIRestoreStatus Status = EKismetAIRestoreStatus::CheckpointUnavailable;
	// Where each side ended up, in words: "checkpoint", "run result",
	// "unchanged", "unknown".
	FString MemoryState;
	FString DiskState;
	FString Explanation;
	TArray<FString> Evidence;
	// The restored state includes edits that were unsaved when the checkpoint
	// was taken; they are now saved.
	bool bIncludesPreviouslyUnsavedEdits = false;

	bool Succeeded() const { return Status == EKismetAIRestoreStatus::Restored; }
	static const TCHAR* StatusToString(EKismetAIRestoreStatus Status);
	TSharedPtr<FJsonObject> ToJson() const;
};

// One checkpoint as listed from disk.
struct FKismetAICheckpointInfo
{
	FString SessionId;
	FString RunId;
	FString AssetPath;
	FString Status;
	FString Directory;
	bool bRestorable = false;
	// The run's latest recorded state differs from the checkpoint.
	bool bChangedByRun = false;
	FDateTime CreatedAt;
};

class FKismetAICheckpointStore
{
public:
	// Root defaults to <Saved>/KismetAI/checkpoints.
	explicit FKismetAICheckpointStore(const FString& InRoot = FString());

	const FString& GetRoot() const { return Root; }

	// Before a run's mutating call to PackagePath: create the run's checkpoint
	// of that asset if there is none, else compare the asset with the run's
	// last recorded state and note a change made outside the run.
	void BeginMutation(const FString& SessionId, const FString& RunId, const FString& PackagePath,
		const FKismetAIAssetFingerprint& Current);

	// After the call: the run's latest state of the asset.
	void EndMutation(const FString& SessionId, const FString& RunId, const FString& PackagePath,
		const FKismetAIAssetFingerprint& Current);

	// Which (asset) Restore puts back: the state before the run, or the state
	// the run left (Reapply after a Restore).
	enum class ETarget : uint8 { BeforeRun, RunResult };

	FKismetAIRestoreReport Restore(const FString& SessionId, const FString& RunId, const FString& PackagePath,
		ETarget Target = ETarget::BeforeRun);

	// Every asset checkpointed for the run. Empty when the run has none.
	TArray<FKismetAICheckpointInfo> ListRun(const FString& SessionId, const FString& RunId) const;
	// Every pending checkpoint, newest run first (recovery after a restart).
	TArray<FKismetAICheckpointInfo> ListPending() const;
	// The newest run of a session that has pending checkpoints; empty if none.
	FString FindLatestPendingRun(const FString& SessionId) const;

	// Mark the run's checkpoints accepted and delete their files.
	void Accept(const FString& SessionId, const FString& RunId);

	// Delete accepted/restored run folders and anything older than MaxAge.
	int32 Prune(FTimespan MaxAge = FTimespan::FromDays(14));

	// ── Test seams ───────────────────────────────────────────────────────────
	enum class EFault : uint8
	{
		None,
		// Writing the checkpoint bytes over the package file fails.
		WriteFails,
		// The package reload after the write fails.
		ReloadFails,
		// ReloadFails, and putting the previous file back fails too.
		ReloadAndRollbackFail,
	};
	struct FScopedFault
	{
		explicit FScopedFault(EFault InFault);
		~FScopedFault();
	};

	// The asset key used in the folder name.
	static FString AssetKey(const FString& PackagePath);
	FString AssetDirectory(const FString& SessionId, const FString& RunId, const FString& PackagePath) const;

private:
	FString Root;

	TSharedPtr<FJsonObject> ReadManifest(const FString& Dir, FString& OutError) const;
	bool WriteManifest(const FString& Dir, const TSharedPtr<FJsonObject>& Manifest) const;
	void AddHistory(const TSharedPtr<FJsonObject>& Manifest, const FString& Event, const FString& Detail) const;
	bool CreateCheckpoint(const FString& Dir, const FString& SessionId, const FString& RunId,
		const FString& PackagePath, const FKismetAIAssetFingerprint& Current);
};
