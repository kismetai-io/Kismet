#!/usr/bin/env python3
"""Embed KismetAI Config/ files into a generated C++ header.

Usage: embed_config.py <config_dir> <out_dir>

Reads every .txt, .json, and .html file under <config_dir> and writes
<out_dir>/EmbeddedConfig.g.inl containing plain UTF-8 byte arrays
plus a hash-keyed lookup table consumed by KismetAIEmbeddedConfig.cpp.
Embedding makes packaged builds self-contained; it does not hide source.
"""
from __future__ import annotations

import hashlib
import sys
from pathlib import Path

EMBED_EXTS = {".txt", ".json", ".html"}

def fnv1a32(data: bytes) -> int:
    h = 0x811C9DC5
    for b in data:
        h ^= b
        h = (h * 0x01000193) & 0xFFFFFFFF
    return h


def name_hash(name: str) -> int:
    return fnv1a32(name.encode("utf-8"))


def emit_bytes(data: bytes) -> str:
    out = []
    for i in range(0, len(data), 16):
        chunk = data[i : i + 16]
        out.append("    " + ",".join(f"0x{b:02x}" for b in chunk) + ",")
    return "\n".join(out)


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: embed_config.py <config_dir> <out_dir>", file=sys.stderr)
        return 2

    config_dir = Path(sys.argv[1]).resolve()
    out_dir = Path(sys.argv[2]).resolve()
    out_dir.mkdir(parents=True, exist_ok=True)

    files = sorted(
        p for p in config_dir.iterdir() if p.is_file() and p.suffix.lower() in EMBED_EXTS
    )

    fingerprint = hashlib.sha256()
    fingerprint.update(b"plain-v2\0")
    for p in files:
        fingerprint.update(p.name.encode("utf-8"))
        fingerprint.update(b"\0")
        fingerprint.update(p.read_bytes())
        fingerprint.update(b"\0")
    stamp = fingerprint.hexdigest()

    out_path = out_dir / "EmbeddedConfig.g.inl"
    stamp_path = out_dir / "EmbeddedConfig.g.stamp"
    if out_path.exists() and stamp_path.exists() and stamp_path.read_text().strip() == stamp:
        return 0

    # Detect hash collisions across the file set. With FNV-1a 32-bit and a
    # handful of files this should never trigger, but a clear error is
    # better than silent lookup failure if it ever does.
    hashes: dict[int, str] = {}
    for p in files:
        h = name_hash(p.name)
        if h in hashes:
            raise SystemExit(
                f"embed_config: fnv1a32 collision between {hashes[h]!r} and {p.name!r} "
                f"(0x{h:08x}); rename one of them."
            )
        hashes[h] = p.name

    lines: list[str] = []
    lines.append("// Auto-generated by embed_config.py — do not edit.")
    lines.append("// Regenerate by building with embed mode on (Scripts/set-embed.sh on,")
    lines.append("// KISMETAI_EMBED_CONFIG=1, or a Shipping/Test configuration).")
    lines.append("// Plain UTF-8 payload; source files are included in release packages.")
    lines.append("")
    lines.append("namespace KismetAIEmbeddedConfig_Generated {")
    lines.append("")
    entries: list[tuple[int, str, int]] = []
    for index, p in enumerate(files):
        plain = p.read_bytes()
        sym = f"Blob_{index}"
        # Source comment keeps the original filename for human review of the
        # generated file. Comments are stripped by the C++ compiler and do
        # not appear in the binary.
        lines.append(f"// {p.name} ({len(plain)} bytes)")
        lines.append(f"static const uint8 {sym}[] = {{")
        if plain:
            lines.append(emit_bytes(plain))
        else:
            # C++ disallows zero-length arrays; emit a single sentinel byte.
            # Entry.Len is 0, so the decode loop never reads it.
            lines.append("    0x00, // placeholder for empty file (Len=0)")
        lines.append("};")
        lines.append("")
        entries.append((name_hash(p.name), sym, len(plain)))

    lines.append("struct FEntry { uint32 NameHash; const uint8* Data; int32 Len; };")
    lines.append("static const FEntry Entries[] = {")
    for h, sym, length in entries:
        lines.append(f"    {{ 0x{h:08x}u, {sym}, {length} }},")
    lines.append("};")
    lines.append(f"static constexpr int32 EntryCount = {len(entries)};")
    lines.append("")
    lines.append("} // namespace KismetAIEmbeddedConfig_Generated")
    lines.append("")

    out_path.write_text("\n".join(lines), encoding="utf-8")
    stamp_path.write_text(stamp, encoding="utf-8")
    print(
        f"[embed_config] wrote {out_path} ({len(entries)} files, "
        f"{sum(e[2] for e in entries)} bytes, plain UTF-8)"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
